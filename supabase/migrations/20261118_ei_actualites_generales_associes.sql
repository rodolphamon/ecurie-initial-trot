-- Messages généraux de l'Écurie Initial : seulement l'administration publie,
-- seuls les associés actifs lisent, jamais les visiteurs.
begin;
create table public.actualites_generales_privees (
 id bigint generated by default as identity primary key,
 titre text not null check (char_length(titre) between 1 and 160),
 contenu text not null default '' check (char_length(contenu)<=6000),
 media_path text,
 media_type text,
 notifier_associes boolean not null default false,
 created_at timestamptz not null default now(),
 constraint ei_actualites_generales_media_check check (
   (media_path is null and media_type is null)
   or (media_path ~ '^general/[0-9a-f-]{36}\.(jpg|png|webp|mp4|webm|mov)$' and media_type in ('image','video'))
 )
);
alter table public.actualites_generales_privees enable row level security;
grant select,insert,delete on public.actualites_generales_privees to authenticated;
grant usage,select on sequence public.actualites_generales_privees_id_seq to authenticated;
create policy "ei lecture actualites generales associes actifs"
 on public.actualites_generales_privees for select to authenticated
 using (public.est_associe_actif());
create policy "ei admin publie actualites generales"
 on public.actualites_generales_privees for insert to authenticated
 with check (public.est_administrateur());
create policy "ei admin supprime actualites generales"
 on public.actualites_generales_privees for delete to authenticated
 using (public.est_administrateur());

insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
 values('ei-generales-privees','ei-generales-privees',false,47185920,
 array['image/jpeg','image/png','image/webp','video/mp4','video/webm','video/quicktime'])
 on conflict (id) do nothing;
create policy "ei media generales lecture associes actifs" on storage.objects
 for select to authenticated
 using (bucket_id='ei-generales-privees' and public.est_associe_actif());
create policy "ei media generales ajout admin" on storage.objects
 for insert to authenticated
 with check (bucket_id='ei-generales-privees' and public.est_administrateur()
 and name ~ '^general/[0-9a-f-]{36}\.(jpg|png|webp|mp4|webm|mov)$');
create policy "ei media generales suppression admin" on storage.objects
 for delete to authenticated
 using (bucket_id='ei-generales-privees' and public.est_administrateur());

alter table public.ei_push_alerts
 drop constraint ei_push_alerts_categorie_check;
alter table public.ei_push_alerts
 add constraint ei_push_alerts_categorie_check check
 (categorie in ('confirmed','daily','before15','results','withdrawn','private_news','preflight_warning','general_news'));

create function public.ei_notify_general_news()
 returns trigger language plpgsql security definer set search_path=''
 as $$
 begin
  if not new.notifier_associes then return new; end if;
  insert into public.ei_push_alerts(id,categorie,cheval_slug,payload,expires_at)
  values('general_news:'||new.id::text,'general_news',null,
    jsonb_build_object('id',new.id),now()+interval '48 hours')
  on conflict(id) do nothing;
  return new;
 end;
 $$;
create trigger ei_actualite_generale_notify_insert
 after insert on public.actualites_generales_privees for each row
 execute function public.ei_notify_general_news();

create function public.ei_expire_general_news()
 returns trigger language plpgsql security definer set search_path=''
 as $$
 begin
  update public.ei_push_alerts set expires_at=least(expires_at,now())
  where id='general_news:'||old.id::text;
  return old;
 end;
 $$;
create trigger ei_actualite_generale_expire_delete
 after delete on public.actualites_generales_privees for each row
 execute function public.ei_expire_general_news();
commit;