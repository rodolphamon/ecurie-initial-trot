-- Espace Entraîneurs: fondation isolée, aucun changement aux rôles existants.
CREATE TABLE IF NOT EXISTS public.ei_entraineurs (
 user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
 nom_entraineur text NOT NULL,
 actif boolean NOT NULL DEFAULT true,
 cree_le timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT nom_entraineur_non_vide CHECK (length(trim(nom_entraineur)) > 2)
);
CREATE TABLE IF NOT EXISTS public.ei_entraineurs_publications (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entraineur_id uuid NOT NULL REFERENCES public.ei_entraineurs(user_id),
 cheval_slug text NOT NULL,
 titre text NOT NULL,
 contenu text NOT NULL DEFAULT '',
 visibilite text NOT NULL DEFAULT 'associes' CHECK (visibilite IN ('associes','public')),
 media_path text,
 media_type text CHECK (media_type IS NULL OR media_type IN ('image','video')),
 cree_le timestamptz NOT NULL DEFAULT now(),
 modifie_le timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT publication_contenu CHECK (length(trim(titre)) BETWEEN 3 AND 150 AND length(contenu) <= 5000),
 CONSTRAINT publication_media CHECK ((media_path IS NULL AND media_type IS NULL) OR (media_path IS NOT NULL AND media_type IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS ei_entraineurs_publications_cheval_idx ON public.ei_entraineurs_publications(cheval_slug,cree_le DESC);
CREATE INDEX IF NOT EXISTS ei_entraineurs_publications_auteur_idx ON public.ei_entraineurs_publications(entraineur_id,cree_le DESC);
ALTER TABLE public.ei_entraineurs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ei_entraineurs_publications ENABLE ROW LEVEL SECURITY;
-- Liste réservée aux utilisateurs connectés et actifs (ne révèle que le nom public et le statut).
CREATE POLICY ei_entraineurs_lire ON public.ei_entraineurs FOR SELECT TO authenticated
 USING (EXISTS (SELECT 1 FROM public.associes a WHERE a.user_id=(SELECT auth.uid()) AND a.actif));
-- Les contenus privés ne sont visibles que des propriétaires du cheval, de l'entraîneur concerné, et de l'administrateur.
CREATE POLICY ei_entraineurs_publications_lire ON public.ei_entraineurs_publications FOR SELECT TO authenticated
 USING (
 EXISTS (SELECT 1 FROM public.associes a WHERE a.user_id=(SELECT auth.uid()) AND a.actif AND (
 a.administrateur
 OR (visibilite='public')
 OR (a.user_id=entraineur_id)
 OR EXISTS (SELECT 1 FROM public.participations_chevaux p WHERE p.user_id=a.user_id AND p.cheval_slug=ei_entraineurs_publications.cheval_slug)
 ))
 );
-- L'entraîneur peut créer uniquement pour les chevaux actuellement actifs et rattachés à son identité.
CREATE POLICY ei_entraineurs_publications_ajouter ON public.ei_entraineurs_publications FOR INSERT TO authenticated
 WITH CHECK (
 entraineur_id=(SELECT auth.uid())
 AND EXISTS (SELECT 1 FROM public.associes a WHERE a.user_id=(SELECT auth.uid()) AND a.actif)
 AND EXISTS (SELECT 1 FROM public.ei_entraineurs t WHERE t.user_id=(SELECT auth.uid()) AND t.actif)
 AND EXISTS (SELECT 1 FROM public.ei_effectif_gestion c JOIN public.ei_entraineurs t ON t.nom_entraineur=c.entraineur
 WHERE t.user_id=(SELECT auth.uid()) AND c.cheval_slug=ei_entraineurs_publications.cheval_slug AND c.actif)
 );
CREATE POLICY ei_entraineurs_publications_modifier ON public.ei_entraineurs_publications FOR UPDATE TO authenticated
 USING (entraineur_id=(SELECT auth.uid()) AND EXISTS (SELECT 1 FROM public.ei_entraineurs t WHERE t.user_id=(SELECT auth.uid()) AND t.actif))
 WITH CHECK (entraineur_id=(SELECT auth.uid()) AND EXISTS (SELECT 1 FROM public.ei_effectif_gestion c JOIN public.ei_entraineurs t ON t.nom_entraineur=c.entraineur WHERE t.user_id=(SELECT auth.uid()) AND t.actif AND c.actif AND c.cheval_slug=ei_entraineurs_publications.cheval_slug));
CREATE POLICY ei_entraineurs_publications_supprimer ON public.ei_entraineurs_publications FOR DELETE TO authenticated
 USING (entraineur_id=(SELECT auth.uid()) OR EXISTS (SELECT 1 FROM public.associes a WHERE a.user_id=(SELECT auth.uid()) AND a.actif AND a.administrateur));
